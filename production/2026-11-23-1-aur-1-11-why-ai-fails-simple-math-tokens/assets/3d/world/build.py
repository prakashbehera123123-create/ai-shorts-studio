ICON_DIR = ROOT / "vendor" / "node_modules" / "lucide-static" / "icons"
ICON_NAMES = ["type", "scissors", "cpu", "calculator", "code", "eye-off", "hash"]


def main() -> None:
    board = json.loads((FOLDER / "storyboard.json").read_text(encoding="utf-8"))
    # scene lengths: the cloned voice's padded scene files are always current after a voice pass; the render report is
    # only a fallback (it can be stale after a script change)
    real = {}
    import subprocess
    for wav in sorted((FOLDER / "voiceover").glob("scene_*_padded.wav")):
        out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(wav)],
                             capture_output=True, text=True).stdout.strip()
        if out:
            real[int(wav.name.split("_")[1])] = round(float(out), 3)
    report = FOLDER / "render" / "render_report.json"
    if not real and report.is_file():
        real = {int(s["id"]): round(s["end"] - s["start"], 3) for s in json.loads(report.read_text(encoding="utf-8")).get("scenes", [])}
    kit = (HERE / "kit.js").read_text(encoding="utf-8")
    world = (HERE / "world.js").read_text(encoding="utf-8")
    title = board.get("video_id", "")
    for s in [x for x in board["scenes"] if x.get("visual", {}).get("project")]:
        sid = int(s["id"])
        dur = real.get(sid) or round(float(s["end_seconds"]) - float(s["start_seconds"]), 3)
        dur = round(dur + 0.2, 3)  # small tail; the overlay trims to the scene
        proj = FOLDER / s["visual"]["project"]
        proj.mkdir(parents=True, exist_ok=True)
        for f in ("hyperframes.json", "package.json"):
            shutil.copy2(TEMPLATE / f, proj / f)
        ids = s.get("source_ids") or []
        src = SOURCES.get(ids[0], "") if ids else ""
        vis = s["visual"]
        cfg = {"shot": int(vis.get("world_shot", sid)), "dur": dur, "pill": s["on_screen_text"], "src": src}
        if vis.get("phase"):
            cfg["phase"] = vis["phase"]
        if vis.get("broll"):
            cfg["broll"] = vis["broll"]
            icons = {n: (ICON_DIR / f"{n}.svg").read_text(encoding="utf-8").split("-->")[-1].strip() for n in ICON_NAMES}
            html = BROLL.format(title=title, shot=sid, dur=dur, cfg=json.dumps(cfg, ensure_ascii=False),
                                icons=json.dumps(icons), broll=(HERE / "broll.js").read_text(encoding="utf-8"))
        else:
            html = PAGE.format(title=title, shot=sid, dur=dur, cfg=json.dumps(cfg, ensure_ascii=False), kit=kit, world=world)
        (proj / "index.html").write_text(html, encoding="utf-8")
        print(f"scene {sid:02d}: {dur}s -> {proj.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
